'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { buildArguments } = require('./build-reading-preview');
const { READING_PREVIEW } = require('../src/shared/reading-preview.cjs');
const args = buildArguments('/tmp/check-preview', 'fixture-signing-identity');
assert(args.includes('-c.appId=com.slipstream.reading-preview'));
assert(args.includes('-c.mac.identity=fixture-signing-identity'));
assert(args.includes('-c.forceCodeSigning=true'));
assert(!args.includes('-c.mac.identity=-'));
assert(args.includes('-c.extraMetadata.slipstreamReadingPreview=true'));
assert(args.includes(`-c.mac.extendInfo.CFBundleDisplayName=${READING_PREVIEW.displayName}`));
const main = fs.readFileSync(path.join(__dirname, '../src/main/main.js'), 'utf8');
assert.match(main, /enabled: app\.isPackaged && !isReadingPreview && runtimeBuildIdentity === BUILD_IDENTITIES\.DEVELOPER_ID/u, 'preview must not receive production auto-updates');
assert.match(main, /const openAtLoginSupported =[^;]+!isReadingPreview/u, 'preview must not manage the installed login item');
const entry = fs.readFileSync(path.join(__dirname, '../src/main/reading-preview-main.js'), 'utf8');
assert.match(entry, /metadata\.slipstreamReadingPreview !== true/u);
assert.match(entry, /metadata\.slipstreamBuildIdentity !== 'developer-id'/u);
console.log('Preview configuration passed: independent identity, required signing, isolated profile, no production updates or login item changes.');
